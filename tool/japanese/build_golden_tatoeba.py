# Builds test/engine/lang/japanese/golden_ja.tsv from Tatoeba's Japanese furigana transcriptions
# (CC BY 2.0 FR, https://tatoeba.org; see docs/notices/japanese.md). Replaces the Aozora corpus,
# whose old spellings mostly are not in Mozc and whose ruby transcriptions have no clear licence.
#
#   curl -L -o transcriptions.tar.bz2 https://downloads.tatoeba.org/exports/transcriptions.tar.bz2
#   (extract transcriptions.csv)
#   python tool/japanese/build_golden_tatoeba.py transcriptions.csv test/engine/lang/japanese/golden_ja.tsv
#
# A transcription marks each kanji run with its reading: "[場所|ば|しょ]へ[行|い]く". An item is a run
# between punctuation made only of hiragana and annotated kanji (no katakana, digits or Latin), with
# at least one annotation and at least 5 characters of reading. Items are spread evenly over the
# file in sentence-id order, at most one per sentence, so the output is deterministic.
import re
import sys

BOUNDARY = re.compile(r'[、。「」『』！？!?…・　,.\s（）()〜~：:；;]')
PIECE = re.compile(r'\[([^\[\]|]+)\|([^\[\]]+)\]')
HIRA = re.compile(r'^[ぁ-ゖー]+$')
KANJI = re.compile(r'^[々一-鿿]+$')


def to_hira(s):
    return ''.join(chr(ord(c) - 0x60) if 'ァ' <= c <= 'ヶ' else c for c in s)


def items_of(sid, text):
    out = []
    # Split on boundaries outside brackets only.
    parts, buf, depth = [], '', 0
    for ch in text:
        if ch == '[':
            depth += 1
        elif ch == ']':
            depth -= 1
        if depth == 0 and BOUNDARY.match(ch):
            parts.append(buf)
            buf = ''
        else:
            buf += ch
    parts.append(buf)
    for part in parts:
        reading, surface, pieces, pos, ok = '', '', [], 0, True
        for m in PIECE.finditer(part):
            gap = part[pos:m.start()]
            if gap and not HIRA.match(gap):
                ok = False
                break
            reading += gap
            surface += gap
            base, rd = m.group(1), to_hira(m.group(2).replace('|', ''))
            if not KANJI.match(base) or not HIRA.match(rd):
                ok = False
                break
            reading += rd
            surface += base
            pieces.append(f'{rd}={base}')
            pos = m.end()
        tail = part[pos:]
        if not ok or (tail and not HIRA.match(tail)) or not pieces:
            continue
        reading += tail
        surface += tail
        if len(reading) >= 5:
            out.append((reading, surface, f'tatoeba:{sid}', ' '.join(pieces)))
    return out


def main(src, dst, count=300):
    rows = []
    with open(src, encoding='utf-8') as f:
        for line in f:
            cols = line.rstrip('\n').split('\t')
            if len(cols) < 5 or cols[1] != 'jpn' or cols[2] != 'Hrkt':
                continue
            rows.append((int(cols[0]), cols[4]))
    rows.sort()
    items = []
    for sid, text in rows:
        found = items_of(sid, text)
        if found:
            items.append(max(found, key=lambda it: len(it[0])))
    if len(items) < count:
        raise SystemExit(f'only {len(items)} items')
    step = len(items) / count
    chosen = [items[int(i * step)] for i in range(count)]
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Golden conversion corpus for the Japanese composer (see docs/notices/japanese.md).\n')
        f.write('# Columns: reading, expected text, source sentence, furigana pieces as reading=surface.\n')
        f.write('# Generated by tool/japanese/build_golden_tatoeba.py from Tatoeba (CC BY 2.0 FR).\n')
        for it in chosen:
            f.write('\t'.join(it) + '\n')
    print(f'sentences {len(rows)}, with items {len(items)}, wrote {count}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
