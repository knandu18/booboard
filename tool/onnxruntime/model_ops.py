# Lists the operators that the staged BooBoard models use, for the reduced onnxruntime build
# (Wave 4-D). Reads the model graphs only (never writes to the staging folder). Subgraphs
# (If, Loop, Scan bodies) are included.
#
# Usage:
#   python tool/onnxruntime/model_ops.py "%USERPROFILE%\.booboard\packs\staging" tool/onnxruntime/model_ops.txt
#
# Output: one line per (domain, operator) used by any model, then the per-model opset imports.
# Needs the onnx package (pip install onnx). Used by check_aar.ps1 for the "every op is in the
# build" check.
import pathlib
import sys

import onnx
from onnx import AttributeProto


def _walk(graph, sink, model_name):
    for node in graph.node:
        domain = node.domain or "ai.onnx"
        sink.setdefault((domain, node.op_type), set()).add(model_name)
        for attr in node.attribute:
            if attr.type == AttributeProto.GRAPH:
                _walk(attr.g, sink, model_name)
            elif attr.type == AttributeProto.GRAPHS:
                for g in attr.graphs:
                    _walk(g, sink, model_name)


def main(staging: str, out_path: str) -> int:
    root = pathlib.Path(staging)
    models = sorted(root.rglob("*.onnx"))
    if not models:
        print(f"no .onnx models under {root}", file=sys.stderr)
        return 1
    ops: dict[tuple[str, str], set[str]] = {}
    imports: list[str] = []
    for path in models:
        name = str(path.relative_to(root)).replace("\\", "/")
        # Graph structure only: external weights are not needed to list operators.
        model = onnx.load(str(path), load_external_data=False)
        opsets = ", ".join(f"{o.domain or 'ai.onnx'}={o.version}" for o in model.opset_import)
        imports.append(f"{name}: {opsets}")
        _walk(model.graph, ops, name)

    lines = [
        "# Operators used by the staged models (generated by tool/onnxruntime/model_ops.py).",
        "# domain;operator;models that use it",
    ]
    for (domain, op), used_by in sorted(ops.items()):
        lines.append(f"{domain};{op};{len(used_by)} model(s)")
    lines.append("")
    lines.append("# Opset imports per model")
    lines.extend(imports)
    text = "\n".join(lines) + "\n"
    pathlib.Path(out_path).write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(models)} models, {len(ops)} distinct operators -> {out_path}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    sys.exit(main(sys.argv[1], sys.argv[2]))
